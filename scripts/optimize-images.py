"""Make responsive WebP copies of the home-page photos, plus the link-preview image.

Run from the project root after adding or replacing a photo in public/images/home/:

    python3 scripts/optimize-images.py

Needs Python 3 with Pillow (`pip install pillow`). The original JPEGs are left untouched and
stay the fallback for browsers without WebP. Writes:
  public/images/home/webp/<name>-<width>.webp   one file per width
  public/images/share/og-image.jpg              1200x630 crop of the hero, for link previews
  src/data/imageWidths.js                       which widths exist, read by src/data/images.js
"""
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / 'public/images/home'
OUT = SRC / 'webp'
WIDTHS = (480, 800, 1200, 1600)
QUALITY = 76

# Only the photos the site actually uses (see src/data/images.js).
FILES = [
    'hero-beauty-in-bloom.jpg', 'signature-portrait.jpg',
    'service-hair.jpg', 'service-skin.jpg', 'service-nails.jpg',
    'service-lashes.jpg', 'service-makeup.jpg', 'service-academy.jpg',
    'gallery-red-lip.jpg', 'gallery-curling.jpg', 'gallery-nails.jpg', 'gallery-glam.jpg',
    'gallery-skin-ritual.jpg', 'gallery-lashes.jpg', 'gallery-curls.jpg',
]


def webp_copies():
    OUT.mkdir(exist_ok=True)
    table = {}
    for name in FILES:
        im = Image.open(SRC / name).convert('RGB')
        top = min(im.width, WIDTHS[-1])
        widths = [w for w in WIDTHS if w < top] + [top]
        for w in widths:
            h = round(im.height * w / im.width)
            im.resize((w, h), Image.LANCZOS).save(OUT / f'{Path(name).stem}-{w}.webp', 'WEBP', quality=QUALITY, method=6)
        table[name] = widths
    return table


def share_image():
    """1200x630 crop from the right of the hero, where the subject and blossoms are."""
    im = Image.open(SRC / 'hero-beauty-in-bloom.jpg').convert('RGB')
    scale = max(630 / im.height, 1200 / im.width)
    im = im.resize((round(im.width * scale), round(im.height * scale)), Image.LANCZOS)
    left = im.width - 1200
    top = round((im.height - 630) * 0.3)
    (ROOT / 'public/images/share').mkdir(exist_ok=True)
    im.crop((left, top, left + 1200, top + 630)).save(ROOT / 'public/images/share/og-image.jpg', 'JPEG', quality=82, optimize=True, progressive=True)


def write_table(table):
    rows = '\n'.join(f"  '{k}': [{', '.join(map(str, v))}]," for k, v in table.items())
    (ROOT / 'src/data/imageWidths.js').write_text(
        '/* Generated by scripts/optimize-images.py — widths of the WebP copies in\n'
        '   public/images/home/webp/. Re-run the script instead of editing by hand. */\n'
        f'export const HOME_WEBP_WIDTHS = {{\n{rows}\n}};\n'
    )


if __name__ == '__main__':
    table = webp_copies()
    share_image()
    write_table(table)
    print(f'{sum(len(v) for v in table.values())} WebP files written to {OUT.relative_to(ROOT)}')
